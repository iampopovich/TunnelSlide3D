import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.Graphics2D;
import java.awt.RenderingHints;
import java.awt.geom.Ellipse2D;
import java.awt.geom.Line2D;
import java.awt.geom.Path2D;
import java.awt.image.BufferedImage;
import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import javax.imageio.ImageIO;

/**
 * Generates the app icon from one geometry description:
 *  - Android adaptive icon foreground + legacy full icon (vector drawables),
 *  - a 512 px PNG for F-Droid / store listings.
 *
 * Run from the repo root:  java tools/IconGen.java
 *
 * Geometry is in the 108x108 adaptive-icon space; the safe zone is a circle of radius 33
 * around (54, 54), everything important stays inside it.
 */
public class IconGen {
    static final String BG = "#070B1A";
    static final String NEON = "#59E6FF";
    static final String CUBE = "#FF3399";
    static final String PLAYER = "#E8FBFF";
    static final double C = 54;
    static final int RINGS = 5;

    static double ringR(int k) { return 30 * Math.pow(0.6, k); }
    static double ringW(int k) { return 3.0 * Math.pow(0.7, k); }
    static double ringA(int k) { return 1.0 - 0.15 * k; }

    // Obstacle cube on the tunnel wall (lower right) and the player's chevron.
    static final double[][] CUBE_PTS = {{60, 59}, {68, 62}, {66, 70}, {58, 67}};
    static final double[][] PLAYER_PTS = {{54, 72}, {62, 84}, {54, 80}, {46, 84}};

    public static void main(String[] args) throws Exception {
        Path res = Path.of("android/src/main/res");
        write(res.resolve("drawable/ic_launcher_foreground.xml"), vector(false));
        write(res.resolve("mipmap-anydpi/ic_launcher.xml"), vector(true));
        write(res.resolve("mipmap-anydpi-v26/ic_launcher.xml"), """
                <?xml version="1.0" encoding="utf-8"?>
                <!-- Generated by tools/IconGen.java -->
                <adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
                    <background android:drawable="@color/ic_launcher_background" />
                    <foreground android:drawable="@drawable/ic_launcher_foreground" />
                    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
                </adaptive-icon>
                """);
        write(res.resolve("values/ic_launcher_colors.xml"), """
                <?xml version="1.0" encoding="utf-8"?>
                <!-- Generated by tools/IconGen.java -->
                <resources>
                    <color name="ic_launcher_background">%s</color>
                </resources>
                """.formatted(BG));
        for (String lang : new String[]{"en-US", "ru"}) {
            Path png = Path.of("fastlane/metadata/android/" + lang + "/images/icon.png");
            Files.createDirectories(png.getParent());
            ImageIO.write(raster(512), "png", png.toFile());
        }
        System.out.println("icon generated");
    }

    static void write(Path p, String s) throws Exception {
        Files.createDirectories(p.getParent());
        Files.writeString(p, s);
    }

    static String f(double v) { return String.format(Locale.ROOT, "%.2f", v); }

    static String circle(double r) {
        return "M" + f(C - r) + "," + f(C) + " a" + f(r) + "," + f(r) + " 0 1,0 " + f(2 * r) + ",0"
                + " a" + f(r) + "," + f(r) + " 0 1,0 " + f(-2 * r) + ",0";
    }

    static String poly(double[][] pts) {
        StringBuilder sb = new StringBuilder("M");
        for (int i = 0; i < pts.length; i++) {
            if (i > 0) sb.append(" L");
            sb.append(f(pts[i][0])).append(',').append(f(pts[i][1]));
        }
        return sb.append(" Z").toString();
    }

    /** Vector drawable; [full] adds the background (legacy icon for Android < 8). */
    static String vector(boolean full) {
        StringBuilder sb = new StringBuilder();
        sb.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/IconGen.java -->\n");
        sb.append("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n");
        sb.append("    android:width=\"108dp\" android:height=\"108dp\"\n");
        sb.append("    android:viewportWidth=\"108\" android:viewportHeight=\"108\">\n");
        if (full) {
            sb.append("    <path android:fillColor=\"").append(BG).append("\" android:pathData=\"").append(circle(50)).append("\" />\n");
        }
        // Spokes from the outer ring to the vanishing point.
        for (int i = 0; i < 8; i++) {
            double a = Math.PI / 4 * i + Math.PI / 8;
            double r = ringR(0);
            sb.append("    <path android:strokeColor=\"").append(NEON).append("\" android:strokeAlpha=\"0.35\" android:strokeWidth=\"1\"")
              .append(" android:pathData=\"M").append(f(C + Math.cos(a) * r)).append(',').append(f(C + Math.sin(a) * r))
              .append(" L").append(f(C)).append(',').append(f(C)).append("\" />\n");
        }
        for (int k = 0; k < RINGS; k++) {
            sb.append("    <path android:strokeColor=\"").append(NEON).append("\" android:strokeAlpha=\"").append(f(ringA(k)))
              .append("\" android:strokeWidth=\"").append(f(ringW(k))).append("\" android:pathData=\"").append(circle(ringR(k))).append("\" />\n");
        }
        sb.append("    <path android:fillColor=\"").append(CUBE).append("\" android:pathData=\"").append(poly(CUBE_PTS)).append("\" />\n");
        sb.append("    <path android:fillColor=\"").append(PLAYER).append("\" android:pathData=\"").append(poly(PLAYER_PTS)).append("\" />\n");
        sb.append("</vector>\n");
        return sb.toString();
    }

    static Color col(String hex, double alpha) {
        Color c = Color.decode(hex);
        return new Color(c.getRed(), c.getGreen(), c.getBlue(), (int) Math.round(alpha * 255));
    }

    /** Full square icon at [size] px, the same drawing as the vector. */
    static BufferedImage raster(int size) {
        BufferedImage img = new BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = img.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        g.setColor(col(BG, 1));
        g.fillRect(0, 0, size, size);
        // Zoom so the 66-unit safe zone fills ~86 % of the square.
        double s = size / 76.0;
        g.translate(size / 2.0, size / 2.0);
        g.scale(s, s);
        g.translate(-C, -C);
        for (int i = 0; i < 8; i++) {
            double a = Math.PI / 4 * i + Math.PI / 8;
            g.setColor(col(NEON, 0.35));
            g.setStroke(new BasicStroke(1f));
            g.draw(new Line2D.Double(C + Math.cos(a) * ringR(0), C + Math.sin(a) * ringR(0), C, C));
        }
        for (int k = 0; k < RINGS; k++) {
            double r = ringR(k);
            g.setColor(col(NEON, ringA(k)));
            g.setStroke(new BasicStroke((float) ringW(k)));
            g.draw(new Ellipse2D.Double(C - r, C - r, 2 * r, 2 * r));
        }
        g.setColor(col(CUBE, 1));
        g.fill(path(CUBE_PTS));
        g.setColor(col(PLAYER, 1));
        g.fill(path(PLAYER_PTS));
        g.dispose();
        return img;
    }

    static Path2D path(double[][] pts) {
        Path2D p = new Path2D.Double();
        p.moveTo(pts[0][0], pts[0][1]);
        for (int i = 1; i < pts.length; i++) p.lineTo(pts[i][0], pts[i][1]);
        p.closePath();
        return p;
    }
}
